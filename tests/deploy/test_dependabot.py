"""``.github/dependabot.yml`` moves the action pins nothing else moves (#90).

#88 pinned setup-uv and auth to commit SHAs, and setup-uv publishes no floating
major tag since v8: without an updater, a security release goes unannounced.
A mistyped Dependabot config stops producing PRs without erroring anywhere a
person looks, so each property is pinned here. CannObserv/watcher's
``tests/ci/test_dependabot.py`` is the template, cut to what broker runs.

* **``github-actions`` only.** ``uv`` is out for #86's reason: co-core resolves
  from the private wheelhouse, which Dependabot's updater cannot sync.
* **The generated cadence workflow is excluded.** ``install-cadence.sh``
  renders ``context-cadence.yml``, and a re-render reverts any bump made in it
  (gregoryfoster/skills#373). ``exclude-paths`` documents no ecosystem limit,
  and dependabot-core applies it in the base fetcher's ``repo_contents``
  (``file_fetchers/base.rb``, read at ``00f6c78``), which the github_actions
  fetcher lists ``.github/workflows/`` through.
* **Every workflow it scans pins each action as ``@<sha> # vX.Y.Z``.**
  Dependabot proposes in the pin's own form, so a SHA and its comment move
  together; a floating tag is what this replaces.
* **The open-PR limit outlasts a full batch**, derived from the workflows:
  past it Dependabot opens nothing and says so nowhere.
* **The prefix is a commit type of AGENTS.md's**, because a Dependabot PR lands
  by fast-forwarding its commit onto ``main`` (docs/CI.md).

Regex over the file, not a YAML parser: this repo carries none, and the config
is small enough to read line by line, as ``test_workflow_pins.py`` reads the
workflows.
"""

from __future__ import annotations

import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONFIG = REPO / ".github" / "dependabot.yml"
WORKFLOWS = REPO / ".github" / "workflows"
CADENCE = WORKFLOWS / "context-cadence.yml"
AGENTS = REPO / "AGENTS.md"

USES = re.compile(r"^[ \t]+(?:- )?uses: (\S+)(.*)$", re.MULTILINE)
SHA_WITH_TAG = re.compile(r"^[\w.-]+/[\w.-]+(?:/[^@\s]*)?@[0-9a-f]{40}$")
TAG_COMMENT = re.compile(r"^ # v\d+\.\d+\.\d+$")


def _config() -> str:
    return CONFIG.read_text() if CONFIG.is_file() else ""


def _scalar(key: str) -> str | None:
    """The value of ``key:`` anywhere in the config, quotes and comment dropped."""
    found = re.findall(rf"^[ \t-]*{re.escape(key)}: \"?([^\"#\s]+)\"?", _config(), re.MULTILINE)
    assert len(found) <= 1, f"{key} appears {len(found)} times"
    return found[0] if found else None


def _sequence(key: str) -> list[str]:
    """The block-sequence items under ``key:``, quotes dropped."""
    block = re.search(rf"^([ \t]*){re.escape(key)}:[ \t]*\n((?:\1[ \t]+- .*\n)*)", _config(), re.M)
    if not block:
        return []
    return [item.strip().strip('"') for item in re.findall(r"- (.*)", block.group(2))]


def _scanned() -> list[Path]:
    """The workflows Dependabot reads: all of them less ``exclude-paths``."""
    excluded = {REPO / p for p in _sequence("exclude-paths")}
    return [p for p in sorted(WORKFLOWS.glob("*.y*ml")) if p not in excluded]


def test_config_exists():
    assert CONFIG.is_file(), "no .github/dependabot.yml: nothing moves the SHA pins (#90)"


def test_config_is_version_2():
    """A version 1 config is ignored without an error."""
    assert _scalar("version") == "2"


def test_only_github_actions_is_configured():
    ecosystems = re.findall(r"package-ecosystem: \"?([\w-]+)", _config())
    assert ecosystems == ["github-actions"], (
        f"{ecosystems}: a `uv` block needs the private wheelhouse reachable from "
        "Dependabot's updater (#86) - its own issue, not this file's"
    )


def test_it_scans_the_workflows_directory():
    """``/`` is the spelling that reads ``.github/workflows/``; any other is silence."""
    assert _scalar("directory") == "/"
    assert _scalar("directories") is None


def test_it_runs_weekly():
    assert _scalar("interval") == "weekly"


def test_it_excludes_exactly_the_generated_cadence_workflow():
    """Relative to ``directory``, so the repo path. Renamed, the exclusion stops
    matching and Dependabot bumps a file the installer will revert."""
    assert _sequence("exclude-paths") == [str(CADENCE.relative_to(REPO))]
    assert "Generated by install-cadence.sh" in CADENCE.read_text()


def test_every_scanned_workflow_pins_each_action_to_a_commit_with_its_tag():
    scanned = _scanned()
    assert {"ci.yml", "audit.yml"} <= {p.name for p in scanned}, scanned
    assert CADENCE not in scanned, scanned
    bad = [
        f"{path.name}: {ref}{rest}"
        for path in scanned
        for ref, rest in USES.findall(path.read_text())
        if not ref.startswith("./") and not (SHA_WITH_TAG.match(ref) and TAG_COMMENT.match(rest))
    ]
    assert not bad, "pin as `owner/action@<40-hex sha> # vX.Y.Z`:\n  " + "\n  ".join(bad)


def test_open_pr_limit_outlasts_a_full_batch():
    """One PR per action. The default is 5."""
    actions = {
        ref.split("@")[0] for path in _scanned() for ref, _ in USES.findall(path.read_text())
    }
    assert actions, "found no `uses:` - the derivation broke"
    limit = int(_scalar("open-pull-requests-limit") or 5)
    assert limit > len(actions), f"limit {limit}, actions {sorted(actions)}"


def test_the_commit_prefix_is_one_of_agents_md_types():
    types = re.search(r"^Types: (.*)\.$", AGENTS.read_text(), re.MULTILINE)
    assert types, "AGENTS.md lost its `Types:` line"
    assert _scalar("prefix") in types.group(1).split(", ")


def test_the_readers_see_what_they_are_given(monkeypatch):
    """The two helpers, against a config in the shape the real one takes."""
    text = (
        'version: 2\nupdates:\n  - package-ecosystem: "github-actions"\n'
        '    exclude-paths:\n      - ".github/workflows/a.yml"\n      - b/**\n'
        "    commit-message:\n      prefix: chore # a comment\n"
    )
    monkeypatch.setattr(f"{__name__}._config", lambda: text)
    assert _sequence("exclude-paths") == [".github/workflows/a.yml", "b/**"]
    assert _scalar("prefix") == "chore"
    assert _scalar("version") == "2"
    assert _sequence("ignore") == []
